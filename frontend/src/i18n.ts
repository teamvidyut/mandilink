export function fmtNum(n: number, lang: Lang): string {
  const locale = lang === 'bn' ? 'bn-IN' : lang === 'hi' ? 'hi-IN' : 'en-IN';
  return new Intl.NumberFormat(locale, { maximumFractionDigits: 1 }).format(n);
}

export function fmtRs(n: number, lang: Lang): string {
  return '₹' + fmtNum(n, lang);
}

export function fmtTime(ms: number, lang: Lang): string {
  const locale = lang === 'bn' ? 'bn-IN' : lang === 'hi' ? 'hi-IN' : 'en-IN';
  const d = new Date(ms);
  const sameDay = new Date().toDateString() === d.toDateString();
  return sameDay
    ? d.toLocaleTimeString(locale, { hour: 'numeric', minute: '2-digit' })
    : d.toLocaleDateString(locale, { day: 'numeric', month: 'short' });
}
